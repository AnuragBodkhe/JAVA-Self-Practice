package ConditionalStatements;

public class if_else_else_if3 {
    public static void main(String[] args){
        int marks = 35;

        if(marks>=60){
            System.out.println("A");
        }else if(marks>=50){
            System.out.println("B");
        }else if(marks>=40){
            System.out.println("C");
        }else{
            System.out.println("Fail");
        }
    }
}
